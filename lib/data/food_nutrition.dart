/// 食物营养表
/// 数据来源:用户提供的中国常见食物营养成分表(每100g)
/// 用于 AI 识别菜品后,根据食材比例计算总营养含量
class FoodNutrition {
  final String name;
  final double energy; // 能量 kcal
  final double protein; // 蛋白质 g
  final double fat; // 脂肪 g
  final double carbs; // 碳水 g
  final double fiber; // 膳食纤维 g

  const FoodNutrition({
    required this.name,
    required this.energy,
    required this.protein,
    required this.fat,
    required this.carbs,
    required this.fiber,
  });

  /// 按克数计算营养(线性比例)
  FoodNutrition scaled(double grams) => FoodNutrition(
        name: name,
        energy: energy * grams / 100,
        protein: protein * grams / 100,
        fat: fat * grams / 100,
        carbs: carbs * grams / 100,
        fiber: fiber * grams / 100,
      );

  Map<String, dynamic> toJson() => {
        'name': name,
        'energy': energy,
        'protein': protein,
        'fat': fat,
        'carbs': carbs,
        'fiber': fiber,
      };

  factory FoodNutrition.fromJson(Map<String, dynamic> json) => FoodNutrition(
        name: json['name'] as String? ?? '',
        energy: (json['energy'] as num?)?.toDouble() ?? 0,
        protein: (json['protein'] as num?)?.toDouble() ?? 0,
        fat: (json['fat'] as num?)?.toDouble() ?? 0,
        carbs: (json['carbs'] as num?)?.toDouble() ?? 0,
        fiber: (json['fiber'] as num?)?.toDouble() ?? 0,
      );
}

